// ตัวเลขใน r.short ตามลำดับ (ใช้เติม {n})
Runes.shortNums = function (r) { return String(this.shortOf(r)).match(/\d+(?:\.\d+)?/g) || []; };
// คำอธิบาย 1 บรรทัดที่ผู้เล่นเห็น: ไทย (เติมเลขจริง) • อังกฤษ = r.short เดิม
Runes.thOf = function (r) {
  if (!r) return '';
  const t = RUNE_TH[r.id], en = this.shortOf(r);
  if (!t) return en;
  const n = this.shortNums(r);
  return L(t.replace(/\{(\d+)\}/g, (m, i) => n[+i] != null ? n[+i] : m), en);
};
